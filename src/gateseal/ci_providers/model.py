"""What every CI provider's file needs from the Lock, and the steps they share.

A writer turns a GateJob into its provider's file. It owns the triggers, the
checkout, the temporary directory, how PATH reaches the next step, the token
source and the mapping from events to gate flags. The pinned downloads, the
preparation and the credential helper's scope are the same for every provider.
Every value the Lock supplies is a JSON-quoted YAML scalar and reaches a script
only through env.
"""

import json
from dataclasses import dataclass

UV_URL = (
    "https://github.com/astral-sh/uv/releases/download/0.13.6/"
    "uv-x86_64-unknown-linux-gnu.tar.gz"
)
UV_SHA256 = "f29c3e94ffabd7e6f3ba521dba169a9b7ec12100bf3257087f0f24f6123f3645"
MISE_URL = (
    "https://github.com/jdx/mise/releases/download/v2026.10.19/"
    "mise-v2026.10.19-linux-x64"
)
MISE_SHA256 = "3162760f40b6b5f706c60641e4ef5ee7322bc6c54f72fc26a7111b337aa18d9d"

GENERATED = (
    "# Generated by gateseal from gateseal.lock. Run gateseal configure to "
    "change it; do not edit it."
)
SCHEDULE = "37 4 * * 1"
IMAGE = "ubuntu-24.04"
TIMEOUT_MINUTES = 30


@dataclass(frozen=True)
class GateJob:
    """The gate of one Lock, before any provider's syntax.

    default_branch is the branch whose pushes the gate checks. python is the
    version that gateseal setup installs pre-commit with. repository and
    commit name the gateseal that the Lock pins. policy_repository is the URL
    of a Git policy, or None for a bundled policy. Each provider decides
    whether its credential helper serves that URL.
    """

    default_branch: str
    python: str
    repository: str
    commit: str
    policy_repository: str | None

    def pins(self) -> dict[str, str]:
        """Return the environment that the preparation reads its pins from."""
        return {
            "GATESEAL_UV_URL": json.dumps(UV_URL),
            "GATESEAL_UV_SHA256": json.dumps(UV_SHA256),
            "GATESEAL_MISE_URL": json.dumps(MISE_URL),
            "GATESEAL_MISE_SHA256": json.dumps(MISE_SHA256),
            "GATESEAL_PYTHON": json.dumps(self.python),
            "GATESEAL_REPOSITORY": json.dumps(self.repository),
            "GATESEAL_COMMIT": json.dumps(self.commit),
        }


def prepare(temporary: str, extend_path: str) -> str:
    """Return the bash script that installs the pinned tools and checks the Lock.

    temporary is the provider's variable for a directory that lasts one job.
    extend_path is the command that puts $tools on PATH for the later steps.
    A fresh agent builds gateseal from the Lock's commit, on the Python that
    gateseal setup installs pre-commit with.
    """
    return f"""\
set -euo pipefail
umask 077
tools="{temporary}/gateseal-tools"
mkdir -p "$tools"
curl --fail --location --silent --show-error "$GATESEAL_UV_URL" \\
  --output "$tools/uv.tar.gz"
echo "$GATESEAL_UV_SHA256  $tools/uv.tar.gz" | sha256sum --check -
tar -xzf "$tools/uv.tar.gz" -C "$tools" --strip-components=1
curl --fail --location --silent --show-error "$GATESEAL_MISE_URL" \\
  --output "$tools/mise"
echo "$GATESEAL_MISE_SHA256  $tools/mise" | sha256sum --check -
chmod 0755 "$tools/uv" "$tools/mise"
export PATH="$tools:$PATH"
{extend_path}
command="{temporary}/gateseal-command"
uv venv --no-config --managed-python --python "$GATESEAL_PYTHON" "$command"
uv pip install --no-config --python "$command/bin/python" \\
  "gateseal @ git+$GATESEAL_REPOSITORY@$GATESEAL_COMMIT"
"$command/bin/gateseal" setup
"$command/bin/gateseal" check
"""


def scoped_helper(repository: str, helper: str) -> dict[str, str]:
    """Return the Git configuration that serves helper's token to repository only.

    The empty helper drops every helper the agent configures, and useHttpPath
    makes Git match the whole URL, so no other repository on the host gets the
    token. manifest.REPOSITORY already keeps the URL to characters a Git
    configuration key can name.
    """
    return {
        "GIT_CONFIG_COUNT": json.dumps("3"),
        "GIT_CONFIG_KEY_0": "credential.useHttpPath",
        "GIT_CONFIG_VALUE_0": json.dumps("true"),
        "GIT_CONFIG_KEY_1": "credential.helper",
        "GIT_CONFIG_VALUE_1": json.dumps(""),
        "GIT_CONFIG_KEY_2": json.dumps(f"credential.{repository}.helper"),
        "GIT_CONFIG_VALUE_2": json.dumps(helper),
    }


def script(lines: str, indent: str) -> list[str]:
    """Return a literal script as the lines of a YAML block scalar's body."""
    return [f"{indent}{line}" if line else "" for line in lines.splitlines()]
